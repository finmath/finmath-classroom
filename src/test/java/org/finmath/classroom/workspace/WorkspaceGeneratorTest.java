package org.finmath.classroom.workspace;

import org.finmath.classroom.io.SafeXml;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.function.Executable;
import org.junit.jupiter.api.io.TempDir;
import org.w3c.dom.Document;
import org.w3c.dom.Element;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class WorkspaceGeneratorTest {
    private static final String NS = "http://maven.apache.org/POM/4.0.0";
    private static final List<String> GENERATED_FILES = List.of("pom.xml", ".idea/vcs.xml", "README.md");

    @TempDir
    Path temporary;
    private Path root;
    private Path manifest;
    private Path output;

    @BeforeEach
    void setUp() throws IOException {
        root = temporary.toRealPath();
        manifest = root.resolve("modules.json");
        output = root.resolve("workspace");
        Files.writeString(manifest, "{\"modules\":[\"one\",\"two\"]}");
        for (String name : List.of("one", "two")) {
            Path directory = Files.createDirectory(root.resolve(name));
            Files.createDirectory(directory.resolve(".git"));
            Files.writeString(directory.resolve("pom.xml"), pom(name));
        }
    }

    @Test
    void generatesIndependentAggregatorAndMappingsWithoutChangingModules() throws Exception {
        Path solution = root.resolve("one/UncommittedSolution.java");
        Files.writeString(solution, "private solution content");
        Map<Path, byte[]> before = Map.of(root.resolve("one/pom.xml"), Files.readAllBytes(root.resolve("one/pom.xml")),
                root.resolve("two/pom.xml"), Files.readAllBytes(root.resolve("two/pom.xml")),
                solution, Files.readAllBytes(solution));
        Files.createDirectory(root.resolve("unlisted-student-copy"));
        Files.writeString(root.resolve("unlisted-student-copy/pom.xml"), "must not be read");

        assertEquals(2, generate(true));
        Document pom = document(output.resolve("pom.xml"));
        assertEquals("pom", pom.getElementsByTagNameNS(NS, "packaging").item(0).getTextContent());
        assertEquals(0, pom.getElementsByTagNameNS(NS, "parent").getLength());
        assertEquals(2, pom.getElementsByTagNameNS(NS, "module").getLength());
        assertEquals("../one", pom.getElementsByTagNameNS(NS, "module").item(0).getTextContent());
        assertEquals("../two", pom.getElementsByTagNameNS(NS, "module").item(1).getTextContent());
        Document vcs = document(output.resolve(".idea/vcs.xml"));
        assertEquals(2, vcs.getElementsByTagName("mapping").getLength());
        assertEquals("$PROJECT_DIR$/../one", ((Element) vcs.getElementsByTagName("mapping").item(0)).getAttribute("directory"));
        assertEquals("$PROJECT_DIR$/../two", ((Element) vcs.getElementsByTagName("mapping").item(1)).getAttribute("directory"));
        assertTrue(Files.readString(output.resolve("README.md")).contains("2 existing repositories"));
        for (Map.Entry<Path, byte[]> entry : before.entrySet()) {
            assertArrayEquals(entry.getValue(), Files.readAllBytes(entry.getKey()));
        }
        assertFalse(Files.exists(root.resolve("one/.idea")));
        assertFalse(Files.exists(root.resolve("two/target")));
    }

    @Test
    void checkCreatesNothing() throws Exception {
        assertEquals(2, generate(false));
        assertFalse(Files.exists(output));
    }

    @Test
    void generatedFilesAreDeterministicAndUnrelatedIdeFilesArePreserved() throws Exception {
        generate(true);
        Map<String, byte[]> before = Map.of("pom.xml", Files.readAllBytes(output.resolve("pom.xml")),
                ".idea/vcs.xml", Files.readAllBytes(output.resolve(".idea/vcs.xml")),
                "README.md", Files.readAllBytes(output.resolve("README.md")));
        Files.writeString(output.resolve(".idea/workspace.xml"), "personal IDE settings");
        assertEquals(2, generate(true));
        for (String file : GENERATED_FILES) {
            assertArrayEquals(before.get(file), Files.readAllBytes(output.resolve(file)));
        }
        assertEquals("personal IDE settings", Files.readString(output.resolve(".idea/workspace.xml")));
    }

    @Test
    void acceptsLegacyPythonOwnershipMarker() throws Exception {
        Files.createDirectories(output.resolve(".idea"));
        for (String file : GENERATED_FILES) {
            Files.writeString(output.resolve(file), "<!-- Generated by finmath-classroom workspace.py -->\nold content\n");
        }
        generate(true);
        for (String file : GENERATED_FILES) {
            String content = Files.readString(output.resolve(file));
            assertTrue(content.contains("<!-- Generated by finmath-classroom workspace -->"));
            assertFalse(content.contains("old content"));
        }
    }

    @Test
    void preflightsAllTargetsBeforeAnyWrite() throws Exception {
        Files.createDirectory(output);
        Files.writeString(output.resolve("README.md"), "My notes");
        rejected(() -> generate(true));
        assertFalse(Files.exists(output.resolve("pom.xml")));
        assertFalse(Files.exists(output.resolve(".idea")));
        assertEquals("My notes", Files.readString(output.resolve("README.md")));
    }

    @Test
    void checkLeavesExistingGeneratedFilesUnchanged() throws Exception {
        generate(true);
        Files.writeString(manifest, "{\"modules\":[\"one\"]}");
        byte[] before = Files.readAllBytes(output.resolve("pom.xml"));
        assertEquals(1, generate(false));
        assertArrayEquals(before, Files.readAllBytes(output.resolve("pom.xml")));
    }

    @Test
    void rejectsInvalidManifestShapesNamesAndDuplicateProperties() throws Exception {
        for (String json : List.of("null", "[]", "{}", "{\"modules\":null}", "{\"modules\":\"one\"}",
                "{\"modules\":[]}", "{\"modules\":[\"one\"],\"other\":true}",
                "{\"modules\":[\"one\",\"one\"]}", "{\"modules\":[\"missing\"]}",
                "{\"modules\":[\"../escape\"]}", "{\"modules\":[\"one/child\"]}",
                "{\"modules\":[\"/one\"]}", "{\"modules\":[\".\"]}", "{\"modules\":[\"..\"]}",
                "{\"modules\":[123]}", "{\"modules\":[\"one\"],\"modules\":[\"two\"]}",
                "{\"modules\":[" + "\"one\",".repeat(200) + "\"two\"]}")) {
            Files.writeString(manifest, json);
            rejected(() -> generate(false));
            assertFalse(Files.exists(output));
        }
    }

    @Test
    void rejectsOversizedManifestAndPom() throws Exception {
        String original = Files.readString(manifest);
        Files.writeString(manifest, original + " ".repeat(256 * 1024));
        rejected(() -> generate(false));
        Files.writeString(manifest, original);
        Files.writeString(root.resolve("one/pom.xml"), pom("one") + " ".repeat(1024 * 1024));
        rejected(() -> generate(false));
    }

    @Test
    void rejectsDuplicateCoordinates() throws Exception {
        Files.writeString(root.resolve("two/pom.xml"), pom("one"));
        Exception exception = rejected(() -> generate(false));
        assertTrue(exception.getMessage().contains("Duplicate Maven coordinates"));
    }

    @Test
    void rejectsInheritedInterpolatedAndInvalidPomCoordinates() throws Exception {
        for (String source : List.of(pom("one").replace("<groupId>example</groupId>", ""),
                pom("one").replace("<version>1.0</version>", "<version>${revision}</version>"),
                pom("one").replace("<artifactId>one</artifactId>", "<artifactId> </artifactId>"),
                pom("one").replace("<artifactId>one</artifactId>", "<artifactId>one</artifactId><artifactId>two</artifactId>"),
                pom("one").replace("<artifactId>one</artifactId>", "<artifactId><unexpected>one</unexpected></artifactId>"),
                pom("one").replace("<groupId>example</groupId>", "<parent><groupId>example</groupId></parent>"),
                pom("one").replace(NS, "urn:not-maven"), "<project")) {
            Files.writeString(root.resolve("one/pom.xml"), source);
            rejected(() -> generate(false));
        }
    }

    @Test
    void rejectsDtdAndEntities() throws Exception {
        Files.writeString(root.resolve("one/pom.xml"), "<!DOCTYPE project [<!ENTITY name SYSTEM \"file:///does-not-exist\">]>"
                + pom("one").replace("<artifactId>one</artifactId>", "<artifactId>&name;</artifactId>"));
        rejected(() -> generate(false));
        assertFalse(Files.exists(output));
    }

    @Test
    void rejectsModuleAndPomSymlinks() throws Exception {
        Path elsewhere = Files.createDirectory(root.resolve("elsewhere"));
        Files.writeString(elsewhere.resolve("pom.xml"), pom("elsewhere"));
        Files.createSymbolicLink(root.resolve("linked"), elsewhere);
        Files.writeString(manifest, "{\"modules\":[\"linked\"]}");
        rejected(() -> generate(false));
        Files.writeString(manifest, "{\"modules\":[\"one\"]}");
        Files.delete(root.resolve("one/pom.xml"));
        Files.createSymbolicLink(root.resolve("one/pom.xml"), elsewhere.resolve("pom.xml"));
        rejected(() -> generate(false));
        assertFalse(Files.exists(output));
    }

    @Test
    void rejectsManifestSymlink() throws Exception {
        Path link = root.resolve("manifest-link.json");
        Files.createSymbolicLink(link, manifest);
        rejected(() -> WorkspaceGenerator.generate(link, root, output, false));
    }

    @Test
    void rejectsOverlappingOutput() {
        for (Path target : List.of(root, root.resolve("one"), root.resolve("one/nested/workspace"))) {
            rejected(() -> WorkspaceGenerator.generate(manifest, root, target, false));
            rejected(() -> WorkspaceGenerator.generate(manifest, root, target, true));
        }
    }

    @Test
    void rejectsSymlinkOutputAndSymlinkParents() throws Exception {
        Path destination = Files.createDirectory(root.resolve("destination"));
        Files.createSymbolicLink(output, destination);
        rejected(() -> generate(true));
        rejected(() -> WorkspaceGenerator.generate(manifest, root, output.resolve("nested"), true));
        try (var children = Files.list(destination)) {
            assertEquals(0, children.count());
        }
    }

    @Test
    void rejectsSymlinkTargetBeforeWritingOtherFiles() throws Exception {
        Files.createDirectories(output.resolve(".idea"));
        Path existing = root.resolve("personal-vcs.xml");
        Files.writeString(existing, "personal settings");
        Files.createSymbolicLink(output.resolve(".idea/vcs.xml"), existing);
        rejected(() -> generate(true));
        assertFalse(Files.exists(output.resolve("pom.xml")));
        assertEquals("personal settings", Files.readString(existing));
    }

    @Test
    void rejectsNonDirectoryIdeaPathBeforeWriting() throws Exception {
        Files.createDirectory(output);
        Files.writeString(output.resolve(".idea"), "not a directory");
        rejected(() -> generate(true));
        assertFalse(Files.exists(output.resolve("pom.xml")));
    }

    @Test
    void gitMappingsIncludeWorktreeFilesAndOmitNonGitModules() throws Exception {
        Files.delete(root.resolve("one/.git"));
        Files.writeString(root.resolve("one/.git"), "gitdir: /example/worktree");
        Files.delete(root.resolve("two/.git"));
        generate(true);
        Document vcs = document(output.resolve(".idea/vcs.xml"));
        assertEquals(1, vcs.getElementsByTagName("mapping").getLength());
        assertEquals("$PROJECT_DIR$/../one", ((Element) vcs.getElementsByTagName("mapping").item(0)).getAttribute("directory"));
    }

    @Test
    void escapesRelativePathsAsXmlTextAndAttributes() throws Exception {
        Path repositories = Files.createDirectory(root.resolve("repositories & \"quotes\""));
        Files.createDirectory(repositories.resolve("one"));
        Files.createDirectory(repositories.resolve("one/.git"));
        Files.writeString(repositories.resolve("one/pom.xml"), pom("one"));
        Files.writeString(manifest, "{\"modules\":[\"one\"]}");
        assertEquals(1, WorkspaceGenerator.generate(manifest, repositories, output, true));
        String relative = "../repositories & \"quotes\"/one";
        assertEquals(relative, document(output.resolve("pom.xml")).getElementsByTagNameNS(NS, "module").item(0).getTextContent());
        Element mapping = (Element) document(output.resolve(".idea/vcs.xml")).getElementsByTagName("mapping").item(0);
        assertEquals("$PROJECT_DIR$/" + relative, mapping.getAttribute("directory"));
    }

    private int generate(boolean write) throws IOException {
        return WorkspaceGenerator.generate(manifest, root, output, write);
    }

    private static String pom(String artifactId) {
        return "<project xmlns=\"" + NS + "\"><modelVersion>4.0.0</modelVersion>"
                + "<groupId>example</groupId><artifactId>" + artifactId + "</artifactId>"
                + "<version>1.0</version></project>";
    }

    private static Document document(Path file) throws IOException {
        return SafeXml.parse(Files.readAllBytes(file));
    }

    private static Exception rejected(Executable action) {
        Exception exception = assertThrows(Exception.class, action);
        assertTrue(exception instanceof IOException || exception instanceof IllegalArgumentException,
                () -> "Expected a validation error, got " + exception.getClass().getName());
        return exception;
    }
}
