package org.finmath.classroom.workspace;

import org.finmath.classroom.io.JsonFiles;
import org.finmath.classroom.io.SafeFiles;
import org.finmath.classroom.io.SafeXml;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import tools.jackson.databind.JsonNode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/** Generates an independent Maven/IntelliJ aggregator without changing its modules. */
public final class WorkspaceGenerator {
    private static final String MARKER = "Generated by finmath-classroom workspace";
    private static final String LEGACY_MARKER = MARKER + ".py";
    private static final String NS = "http://maven.apache.org/POM/4.0.0";
    private static final int MANIFEST_LIMIT = 256 * 1024;
    private static final int POM_LIMIT = 1024 * 1024;
    private static final Pattern MODULE_NAME = Pattern.compile("[A-Za-z0-9][A-Za-z0-9_.-]{0,150}");

    private WorkspaceGenerator() {
    }

    /** Validates the explicit module list and optionally writes the three generated files. */
    public static int generate(Path manifest, Path repositoriesRoot, Path output, boolean write)
            throws IOException {
        if (manifest == null || repositoriesRoot == null || output == null) {
            throw new IllegalArgumentException("Manifest, repositories root and output are required");
        }
        Path repositories = repositoriesRoot.toRealPath();
        if (!Files.isDirectory(repositories, LinkOption.NOFOLLOW_LINKS)) {
            throw new IllegalArgumentException("Repositories root must be a directory");
        }
        List<Path> modules = inspectModules(manifest, repositories);
        Path workspace = output.toAbsolutePath().normalize();
        checkDirectoryPath(workspace);
        for (Path module : modules) {
            if (workspace.startsWith(module) || module.startsWith(workspace)) {
                throw new IllegalArgumentException("Workspace must not overlap an assignment repository: " + module);
            }
        }
        Map<String, String> files = render(modules, workspace);
        if (write) {
            // Validate every target before creating directories or replacing any file.
            for (String name : files.keySet()) {
                checkOwnedTarget(workspace.resolve(name));
            }
            for (Map.Entry<String, String> file : files.entrySet()) {
                Path target = workspace.resolve(file.getKey());
                checkOwnedTarget(target);
                Files.createDirectories(target.getParent());
                SafeFiles.writeAtomic(target, file.getValue().getBytes(StandardCharsets.UTF_8), true);
            }
        }
        return modules.size();
    }

    private static List<Path> inspectModules(Path manifest, Path repositories) throws IOException {
        JsonNode config = JsonFiles.read(manifest, MANIFEST_LIMIT);
        if (config == null || !config.isObject() || config.size() != 1 || !config.has("modules")) {
            throw new IllegalArgumentException("Manifest must contain only a modules list");
        }
        JsonNode names = config.get("modules");
        if (!names.isArray() || names.size() < 1 || names.size() > 200) {
            throw new IllegalArgumentException("Expected 1 to 200 explicit module names");
        }
        List<Path> paths = new ArrayList<>();
        Set<String> seenNames = new HashSet<>();
        Set<Coordinates> seenCoordinates = new HashSet<>();
        for (JsonNode entry : names) {
            if (!entry.isTextual() || !MODULE_NAME.matcher(entry.asString()).matches()) {
                throw new IllegalArgumentException("Each module must be a simple sibling directory name");
            }
            String name = entry.asString();
            if (!seenNames.add(name)) {
                throw new IllegalArgumentException("Duplicate module: " + name);
            }
            Path directory = repositories.resolve(name);
            if (Files.isSymbolicLink(directory) || !Files.isDirectory(directory, LinkOption.NOFOLLOW_LINKS)) {
                throw new IllegalArgumentException("Module must be a direct, non-symlink sibling: " + name);
            }
            directory = directory.toRealPath();
            if (!repositories.equals(directory.getParent())) {
                throw new IllegalArgumentException("Module must be a direct, non-symlink sibling: " + name);
            }
            Path pom = directory.resolve("pom.xml");
            Element project = SafeXml.parse(SafeFiles.read(pom, POM_LIMIT)).getDocumentElement();
            if (!NS.equals(project.getNamespaceURI()) || !"project".equals(project.getLocalName())) {
                throw new IllegalArgumentException("Expected a Maven POM: " + pom);
            }
            Coordinates coordinates = new Coordinates(
                    literalCoordinate(project, "groupId", name),
                    literalCoordinate(project, "artifactId", name),
                    literalCoordinate(project, "version", name));
            if (!seenCoordinates.add(coordinates)) {
                throw new IllegalArgumentException("Duplicate Maven coordinates: " + coordinates.groupId()
                        + ":" + coordinates.artifactId() + ":" + coordinates.version());
            }
            paths.add(directory);
        }
        return paths;
    }

    private static String literalCoordinate(Element project, String field, String module) {
        String value = null;
        for (Node child = project.getFirstChild(); child != null; child = child.getNextSibling()) {
            if (child instanceof Element element && NS.equals(element.getNamespaceURI())
                    && field.equals(element.getLocalName())) {
                if (value != null) {
                    throw new IllegalArgumentException("Duplicate Maven coordinate " + field + " in " + module);
                }
                for (Node part = element.getFirstChild(); part != null; part = part.getNextSibling()) {
                    if (part instanceof Element) {
                        throw new IllegalArgumentException("Module needs explicit literal Maven coordinates: " + module);
                    }
                }
                value = element.getTextContent().strip();
            }
        }
        if (value == null || value.isEmpty() || value.contains("${")) {
            throw new IllegalArgumentException("Module needs explicit literal Maven coordinates: " + module);
        }
        return value;
    }

    private static Map<String, String> render(List<Path> modules, Path output) {
        StringBuilder pom = new StringBuilder(xmlHeader()).append("<project xmlns=\"").append(NS).append("\">\n")
                .append("  <modelVersion>4.0.0</modelVersion>\n")
                .append("  <groupId>org.finmath.classroom</groupId>\n")
                .append("  <artifactId>finmath-lectures-workspace</artifactId>\n")
                .append("  <version>1.0-SNAPSHOT</version>\n")
                .append("  <packaging>pom</packaging>\n")
                .append("  <name>finmath lecture workspace (aggregation only)</name>\n")
                .append("  <modules>\n");
        StringBuilder vcs = new StringBuilder(xmlHeader()).append("<project version=\"4\">\n")
                .append("  <component name=\"VcsDirectoryMappings\">\n");
        for (Path module : modules) {
            String relative = output.relativize(module).toString().replace(module.getFileSystem().getSeparator(), "/");
            pom.append("    <module>").append(xml(relative)).append("</module>\n");
            if (Files.exists(module.resolve(".git"))) {
                vcs.append("    <mapping directory=\"$PROJECT_DIR$/").append(xml(relative))
                        .append("\" vcs=\"Git\" />\n");
            }
        }
        pom.append("  </modules>\n</project>\n");
        vcs.append("  </component>\n</project>\n");
        Map<String, String> files = new LinkedHashMap<>();
        files.put("pom.xml", pom.toString());
        files.put(".idea/vcs.xml", vcs.toString());
        files.put("README.md", "<!-- " + MARKER + " -->\n# finmath lecture workspace\n\n"
                + "Open `pom.xml` in IntelliJ IDEA as a project. It aggregates " + modules.size() + " existing repositories.\n\n"
                + "This is a generated local workspace, not a shared Maven parent or a merged Git repository. "
                + "Edits in a module affect its existing working tree. Commit per repository.\n\n"
                + "The source module list and generator live in `../finmath-classroom`. "
                + "Do not add student copies or solution repositories automatically. "
                + "Do not run a workspace-wide build unless you intend to run all assignment builds.\n");
        return files;
    }

    private static String xmlHeader() {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- " + MARKER + " -->\n";
    }

    private static String xml(String value) {
        StringBuilder escaped = new StringBuilder();
        value.codePoints().forEach(codePoint -> {
            switch (codePoint) {
                case '&' -> escaped.append("&amp;");
                case '<' -> escaped.append("&lt;");
                case '>' -> escaped.append("&gt;");
                case '"' -> escaped.append("&quot;");
                case '\'' -> escaped.append("&apos;");
                case '\t' -> escaped.append("&#9;");
                case '\n' -> escaped.append("&#10;");
                case '\r' -> escaped.append("&#13;");
                default -> {
                    if (codePoint < 0x20 || (codePoint >= 0xD800 && codePoint <= 0xDFFF)
                            || codePoint == 0xFFFE || codePoint == 0xFFFF) {
                        throw new IllegalArgumentException("Workspace paths must contain valid XML characters");
                    }
                    escaped.appendCodePoint(codePoint);
                }
            }
        });
        return escaped.toString();
    }

    private static void checkDirectoryPath(Path directory) {
        for (Path path = directory; path != null; path = path.getParent()) {
            if (Files.isSymbolicLink(path)) {
                throw new IllegalArgumentException("Workspace paths must not traverse symlinks: " + path);
            }
            if (Files.exists(path, LinkOption.NOFOLLOW_LINKS)
                    && !Files.isDirectory(path, LinkOption.NOFOLLOW_LINKS)) {
                throw new IllegalArgumentException("Workspace parent must be a directory: " + path);
            }
        }
    }

    private static void checkOwnedTarget(Path target) throws IOException {
        checkDirectoryPath(target.getParent());
        if (Files.isSymbolicLink(target)) {
            throw new IllegalArgumentException("Workspace target must not be a symlink: " + target);
        }
        if (Files.exists(target, LinkOption.NOFOLLOW_LINKS)) {
            byte[] content = SafeFiles.read(target, POM_LIMIT);
            String beginning = new String(content, 0, Math.min(300, content.length), StandardCharsets.UTF_8);
            if (!beginning.contains("<!-- " + MARKER + " -->")
                    && !beginning.contains("<!-- " + LEGACY_MARKER + " -->")) {
                throw new IllegalArgumentException("Refusing to overwrite a file not generated by this tool: " + target);
            }
        }
    }

    private record Coordinates(String groupId, String artifactId, String version) {
    }
}
